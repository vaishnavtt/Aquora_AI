"""
Tests for the ML Prediction Service Interface and Pluggability Architecture (Task 8).
Verifies that the ML lead can integrate a trained model without altering API routes.
"""

import pytest
try:
    from app.ml.base import BaseRiskPredictor
    from app.ml.predictor import prediction_service, BaselineHeuristicPredictor
    from app.schemas.prediction import PredictRequest, PredictResponse
except ImportError:
    from backend.app.ml.base import BaseRiskPredictor
    from backend.app.ml.predictor import prediction_service, BaselineHeuristicPredictor
    from backend.app.schemas.prediction import PredictRequest, PredictResponse

class DummyTrainedMLPredictor(BaseRiskPredictor):
    """Simulates a trained scikit-learn model wrapped by the ML Lead."""

    @property
    def version(self) -> str:
        return "aquora-randomforest-v1.0-trained"

    @property
    def is_trained(self) -> bool:
        return True

    def predict(self, req: PredictRequest) -> PredictResponse:
        # Custom mock inference logic simulating a trained pipeline
        return PredictResponse(
            risk_score=42.0,
            risk_level="moderate",
            confidence=0.94,
            primary_hazards=["Simulated ML Feature Contribution: Current Flow"],
            safety_recommendations=["Advisory generated by trained scikit-learn model."],
            model_version=self.version,
            is_baseline_model=False,
            ai_explanation=None
        )

def test_base_predictor_is_abstract():
    """Verifies that BaseRiskPredictor cannot be instantiated directly."""
    with pytest.raises(TypeError):
        BaseRiskPredictor()

def test_default_service_is_baseline_heuristic():
    """Verifies default prediction service defaults to baseline heuristic."""
    assert isinstance(prediction_service._active_predictor, BaselineHeuristicPredictor)
    assert prediction_service.is_trained is False
    assert prediction_service.version == "baseline-heuristic-v0.1"

def test_register_trained_model_pluggability(client):
    """
    Verifies that registering a new predictor immediately changes prediction
    and health endpoint output without touching API routes.
    """
    try:
        # Register the dummy trained model
        trained_predictor = DummyTrainedMLPredictor()
        prediction_service.register_predictor(trained_predictor)

        assert prediction_service.is_trained is True
        assert prediction_service.version == "aquora-randomforest-v1.0-trained"

        # Verify /api/v1/health now reports ml_model_loaded == True
        health_res = client.get("/api/v1/health")
        assert health_res.status_code == 200
        assert health_res.json()["ml_model_loaded"] is True

        # Verify /api/v1/predict now executes through the trained model
        pred_res = client.post("/api/v1/predict", json={
            "water_temp_c": 19.0,
            "flow_rate_cms": 2.0,
            "depth_meters": 3.0,
            "rainfall_last_24h_mm": 5.0,
            "wind_speed_kmh": 10.0,
            "visibility_meters": 2000.0
        })
        assert pred_res.status_code == 200
        data = pred_res.json()
        assert data["is_baseline_model"] is False
        assert data["model_version"] == "aquora-randomforest-v1.0-trained"
        assert data["confidence"] == 0.94
        assert data["risk_score"] == 42.0
    finally:
        # Restore baseline for subsequent tests
        prediction_service.reset_to_baseline()
        assert prediction_service.is_trained is False

def test_register_invalid_predictor_type_raises():
    """Verifies that registering an invalid non-BaseRiskPredictor object raises TypeError."""
    with pytest.raises(TypeError):
        prediction_service.register_predictor("not_a_predictor")
